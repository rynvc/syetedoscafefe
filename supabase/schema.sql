create or replace function public.current_user_is_owner()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where user_id = auth.uid() and role = 'owner' and active
  );
$$;
revoke all on function public.current_user_is_owner() from public;
grant execute on function public.current_user_is_owner() to authenticated;

create or replace function public.create_profile_for_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  profile_username text;
begin
  profile_username := coalesce(
    nullif(new.raw_user_meta_data ->> 'username', ''),
    split_part(new.email, '@', 1)
  );

  insert into public.profiles (user_id, username, full_name, email)
  values (
    new.id,
    profile_username,
    coalesce(new.raw_user_meta_data ->> 'full_name', profile_username),
    new.email
  )
  on conflict (user_id) do update
    set email = excluded.email;
  return new;
end;
$$;
revoke all on function public.create_profile_for_auth_user() from public;

drop trigger if exists create_profile_after_signup on auth.users;
create trigger create_profile_after_signup
  after insert on auth.users
  for each row execute procedure public.create_profile_for_auth_user();

