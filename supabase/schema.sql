create or replace function public.record_sale(
  p_items jsonb,
  p_payment_method text,
  p_amount_tendered numeric,
  p_payment_confirmed boolean
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  current_profile public.profiles%rowtype;
  current_item jsonb;
  found_product public.products%rowtype;
  sale_key bigint;
  item_quantity integer;
  line_price numeric(10,2);
  computed_total numeric(12,2) := 0;
  computed_change numeric(12,2);
  item_result jsonb := '[]'::jsonb;
begin
  select * into current_profile from public.profiles
  where user_id = auth.uid() and active;
  if not found then
    raise exception 'An active signed-in account is required.';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Add at least one item before recording a sale.';
  end if;
  if p_payment_method is null or p_payment_method not in ('Cash', 'GCash')
      or p_amount_tendered is null or p_amount_tendered < 0 then
    raise exception 'Unsupported payment method.';
  end if;

  for current_item in select value from jsonb_array_elements(p_items)
  loop
    item_quantity := (current_item ->> 'quantity')::integer;
    if item_quantity <= 0 then
      raise exception 'Item quantity must be positive.';
    end if;
    select * into found_product from public.products
    where product_id = (current_item ->> 'product_id')::bigint for share;
    if not found then
      raise exception 'A menu item no longer exists.';
    end if;
    line_price := found_product.price;
    computed_total := computed_total + line_price * item_quantity;
  end loop;

  if p_payment_method = 'Cash' and p_amount_tendered < computed_total then
    raise exception 'Cash tendered does not cover the sale total.';
  end if;
  if p_payment_method = 'GCash' and (not coalesce(p_payment_confirmed, false)
      or p_amount_tendered < computed_total) then
    raise exception 'Confirm the received GCash payment before completing checkout.';
  end if;

  computed_change := case when p_payment_method = 'Cash'
    then p_amount_tendered - computed_total else 0 end;

  insert into public.sales (
    user_id, total, payment_method, amount_tendered, change_due, payment_confirmed
  ) values (
    current_profile.user_id, computed_total, p_payment_method,
    p_amount_tendered, computed_change, true
  ) returning sale_id into sale_key;

  for current_item in select value from jsonb_array_elements(p_items)
  loop
    item_quantity := (current_item ->> 'quantity')::integer;
    select * into found_product from public.products
    where product_id = (current_item ->> 'product_id')::bigint for share;
    line_price := found_product.price;
    insert into public.sale_items (
      sale_id, product_id, name, category, quantity, price
    ) values (
      sale_key, found_product.product_id, found_product.name,
      found_product.category_name, item_quantity, line_price
    );
    item_result := item_result || jsonb_build_array(jsonb_build_object(
      'product_id', found_product.product_id,
      'name', found_product.name,
      'category', found_product.category_name,
      'quantity', item_quantity,
      'price', line_price
    ));
  end loop;

  return jsonb_build_object(
    'id', sale_key,
    'items', item_result,
    'total', computed_total,
    'paymentMethod', p_payment_method,
    'amountTendered', p_amount_tendered,
    'change', computed_change,
    'paymentConfirmed', true,
    'createdAt', now()
  );
end;
$$;

create or replace function public.import_legacy_sale(p_sale jsonb)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  current_item jsonb;
  sale_key bigint;
  old_id text;
  legacy_total numeric(12,2);
  payment text;
  tender numeric(12,2);
  confirmed boolean;
  item_quantity integer;
  item_price numeric(10,2);
  item_result jsonb := '[]'::jsonb;
begin
  if not public.current_user_is_owner() then
    raise exception 'Only an owner can import historical sales.';
  end if;
  old_id := 'legacy:' || (p_sale ->> 'id');
  select sale_id into sale_key from public.sales where legacy_id = old_id;
  if found then return sale_key; end if;

  legacy_total := (p_sale ->> 'total')::numeric;
  payment := coalesce(p_sale ->> 'paymentMethod', 'Cash');
  tender := coalesce((p_sale ->> 'amountTendered')::numeric, legacy_total);
  confirmed := coalesce((p_sale ->> 'paymentConfirmed')::boolean, true);
  if payment not in ('Cash', 'GCash') or legacy_total < 0 or tender < 0 then
    raise exception 'A historical sale has invalid payment data.';
  end if;
  if jsonb_typeof(p_sale -> 'items') = 'array' then
    for current_item in select value from jsonb_array_elements(p_sale -> 'items')
    loop
      item_quantity := (current_item ->> 'quantity')::integer;
      item_price := (current_item ->> 'price')::numeric;
      if item_quantity <= 0 or item_price < 0 then
        raise exception 'A historical sale has invalid item data.';
      end if;
      item_result := item_result || jsonb_build_array(jsonb_build_object(
        'item', current_item, 'quantity', item_quantity, 'price', item_price
      ));
    end loop;
  end if;

  insert into public.sales (
    legacy_id, user_id, created_at, total, payment_method,
    amount_tendered, change_due, payment_confirmed
  ) values (
    old_id, auth.uid(),
    coalesce((p_sale ->> 'createdAt')::timestamptz, now()),
    legacy_total, payment, tender,
    coalesce((p_sale ->> 'change')::numeric, 0), confirmed
  ) returning sale_id into sale_key;

  for current_item in select value from jsonb_array_elements(item_result)
  loop
    insert into public.sale_items (
      sale_id, name, category, quantity, price
    ) values (
      sale_key,
      coalesce(current_item -> 'item' ->> 'name', 'Historical item'),
      coalesce(current_item -> 'item' ->> 'category', 'General'),
      (current_item ->> 'quantity')::integer,
      (current_item ->> 'price')::numeric
    );
  end loop;
  return sale_key;
end;
$$;

