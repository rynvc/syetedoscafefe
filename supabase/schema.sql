create extension if not exists pgcrypto;

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  full_name text not null default '',
  email text not null unique,
  role text not null default 'cashier' check (role in ('owner', 'cashier')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  product_id bigint generated by default as identity primary key,
  legacy_id bigint unique,
  name text not null unique,
  category_name text not null default 'General',
  price numeric(10,2) not null check (price >= 0),
  supplier text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.sales (
  sale_id bigint generated by default as identity primary key,
  legacy_id text unique,
  user_id uuid not null references public.profiles(user_id),
  created_at timestamptz not null default now(),
  total numeric(12,2) not null check (total >= 0),
  payment_method text not null check (payment_method in ('Cash', 'GCash')),
  amount_tendered numeric(12,2) not null check (amount_tendered >= 0),
  change_due numeric(12,2) not null default 0 check (change_due >= 0),
  payment_confirmed boolean not null default false
);

create table if not exists public.sale_items (
  sale_item_id bigint generated by default as identity primary key,
  sale_id bigint not null references public.sales(sale_id) on delete cascade,
  product_id bigint references public.products(product_id) on delete set null,
  name text not null,
  category text not null default 'General',
  quantity integer not null check (quantity > 0),
  price numeric(10,2) not null check (price >= 0)
);

create index if not exists sales_created_at_idx on public.sales(created_at);
create index if not exists sale_items_sale_id_idx on public.sale_items(sale_id);

